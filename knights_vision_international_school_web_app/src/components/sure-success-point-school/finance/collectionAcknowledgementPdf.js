"use client";

import { jsPDF } from "jspdf";

const money = new Intl.NumberFormat("en-IN", {
  style: "currency",
  currency: "INR",
  maximumFractionDigits: 2,
});

function studentName(student) {
  return [student?.firstName, student?.middleName, student?.lastName].filter(Boolean).join(" ") || "Student";
}

function safeText(value, fallback = "Not recorded") {
  const text = String(value ?? "").trim();
  return text || fallback;
}

export function downloadCollectionAcknowledgementPdf({ collection, student, classLabel = "Not recorded" }) {
  if (!collection || !student) return;
  const isAdmission = ["NEW_ADMISSION", "READMISSION"].includes(collection.paymentKind);
  const document = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const receiptNumber = safeText(collection.publicId);
  const paymentLabel = collection.paymentKind === "READMISSION"
    ? "Readmission Fee"
    : collection.paymentKind === "NEW_ADMISSION"
      ? "Admission Fee"
      : "Monthly Fee";
  const collectedAt = collection.collectedAt ? new Date(collection.collectedAt) : new Date();
  const line = (label, value, y) => {
    document.setFont("helvetica", "bold");
    document.text(`${label}:`, 20, y);
    document.setFont("helvetica", "normal");
    document.text(safeText(value), 63, y, { maxWidth: 120 });
  };

  document.setFillColor(18, 51, 33);
  document.rect(0, 0, 210, 34, "F");
  document.setTextColor(255, 255, 255);
  document.setFont("helvetica", "bold");
  document.setFontSize(18);
  document.text("Sure Success Point School", 105, 15, { align: "center" });
  document.setFontSize(10);
  document.text(isAdmission ? "Admission Payment Acknowledgement" : "Fee Collection Acknowledgement", 105, 23, { align: "center" });
  document.setFont("helvetica", "normal");
  document.setFontSize(8);
  document.text("Guardian paid - school custody tracking copy", 105, 29, { align: "center" });

  document.setTextColor(25, 25, 25);
  document.setFontSize(11);
  document.setFont("helvetica", "bold");
  document.text("PAYMENT RECEIVED FROM GUARDIAN", 20, 47);
  document.setFont("helvetica", "normal");
  document.setFontSize(10);
  let y = 59;
  line("Acknowledgement no.", receiptNumber, y); y += 9;
  line("Student", studentName(student), y); y += 9;
  line("Admission no.", student.admissionNumber, y); y += 9;
  line("Class", classLabel, y); y += 9;
  line("Fee item", paymentLabel, y); y += 9;
  line("Amount received", money.format(Number(collection.amount || 0)), y); y += 9;
  line("Method", collection.method, y); y += 9;
  line("Payment reference", collection.transactionId || "Cash collection", y); y += 9;
  line("Collected on", collectedAt.toLocaleString("en-IN"), y); y += 13;

  document.setFillColor(255, 244, 205);
  document.roundedRect(18, y - 5, 174, 33, 2, 2, "F");
  document.setTextColor(90, 70, 10);
  document.setFont("helvetica", "bold");
  document.setFontSize(10);
  document.text("Important school-custody status", 23, y + 4);
  document.setFont("helvetica", "normal");
  document.setFontSize(9);
  const note = "The guardian has paid the stated amount to the school collector. The amount is marked as collected and reserved against this fee. It remains subject to collector handover, COEF verification, school-bank submission, and Central Administration confirmation before the final ledger receipt is issued.";
  document.text(document.splitTextToSize(note, 162), 23, y + 11);

  document.setTextColor(25, 25, 25);
  document.setFontSize(9);
  document.text("Collector signature", 20, 258);
  document.line(20, 254, 78, 254);
  document.text("Guardian signature", 132, 258);
  document.line(132, 254, 190, 254);
  document.setFontSize(8);
  document.setTextColor(110, 110, 110);
  document.text("This acknowledgement is system generated by Sure Success Point School.", 105, 278, { align: "center" });

  const filePrefix = isAdmission ? "SSPS-Admission-Payment-Acknowledgement" : "SSPS-Fee-Collection-Acknowledgement";
  document.save(`${filePrefix}-${safeText(student.admissionNumber, "Student")}.pdf`);
}
