import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

const darkGreen = [20, 67, 45];
const gold = [214, 168, 61];
const dark = [28, 31, 34];

function text(value, fallback = "Not recorded") {
  const result = String(value ?? "").trim();
  return result || fallback;
}

function date(value, fallback = "Not recorded") {
  if (!value) return fallback;
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime()) ? fallback : new Intl.DateTimeFormat("en-IN", { day: "2-digit", month: "long", year: "numeric" }).format(parsed);
}

function month(value) {
  if (!value) return "Not recorded";
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime()) ? "Not recorded" : new Intl.DateTimeFormat("en-IN", { month: "long", year: "numeric" }).format(parsed);
}

function money(value) {
  const amount = Number(value || 0);
  return new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 2 }).format(Number.isFinite(amount) ? amount : 0);
}

function documentCode(type, employee, reference) {
  const prefix = type.replaceAll("_", "-").slice(0, 18);
  return text(reference, `${prefix}/SSPS/${employee.id}/${new Date().getFullYear()}`);
}

function header(doc, title, employee, reference, confidential = false) {
  doc.setFillColor(...darkGreen);
  doc.rect(0, 0, 210, 32, "F");
  doc.setFillColor(...gold);
  doc.rect(0, 30, 210, 2, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(17);
  doc.text("Sure Success Point School", 18, 14);
  doc.setFontSize(8.5);
  doc.setFont("helvetica", "normal");
  doc.text("Central Administration • Human Resources", 18, 21);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(title.toUpperCase(), 192, 15, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  doc.text(confidential ? "CONFIDENTIAL HR RECORD" : "OFFICIAL HR DOCUMENT", 192, 21, { align: "right" });

  doc.setTextColor(...dark);
  doc.setFontSize(8.5);
  doc.text(`Reference: ${reference}`, 18, 42);
  doc.text(`Generated: ${date(new Date())}`, 192, 42, { align: "right" });
  doc.setDrawColor(215, 215, 215);
  doc.line(18, 46, 192, 46);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(105, 105, 105);
  doc.text(`Employee ID: ${employee.id}  •  ${text(employee.school?.name, "Sure Success Point School")}`, 18, 51);
}

function footer(doc, reference, confidential = false) {
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page);
    doc.setDrawColor(220, 220, 220);
    doc.line(18, 281, 192, 281);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(115, 115, 115);
    doc.text(confidential ? "Confidential: issued for the named employee and authorised institution use only." : "System-generated by Sure Success Point School Central Administration.", 18, 286);
    doc.text(`${reference}  •  Page ${page} of ${pages}`, 192, 286, { align: "right" });
  }
}

function signature(doc, y, signatory) {
  doc.setDrawColor(80, 80, 80);
  doc.line(132, y, 190, y);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(...dark);
  doc.text(text(signatory, "Authorised Signatory"), 161, y + 6, { align: "center" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  doc.setTextColor(105, 105, 105);
  doc.text("Sure Success Point School", 161, y + 11, { align: "center" });
}

function paragraph(doc, value, y, width = 174, size = 10) {
  doc.setFont("helvetica", "normal");
  doc.setFontSize(size);
  doc.setTextColor(...dark);
  const lines = doc.splitTextToSize(value, width);
  doc.text(lines, 18, y);
  return y + lines.length * (size * 0.48);
}

function staffDetails(doc, employee, y) {
  autoTable(doc, {
    startY: y,
    theme: "grid",
    margin: { left: 18, right: 18 },
    styles: { font: "helvetica", fontSize: 8.5, cellPadding: 2.6, textColor: dark },
    headStyles: { fillColor: darkGreen, textColor: 255, fontStyle: "bold" },
    body: [
      ["Employee", text(employee.username), "Department", text(employee.department)],
      ["Designation", text(employee.designation || employee.role || employee.roleHistory?.[0]?.role?.name), "School / branch", `${text(employee.school?.name)}${employee.branch?.name ? ` / ${employee.branch.name}` : ""}`],
      ["Engagement record", date(employee.joiningDate || employee.createdAt), "Account state", employee.isActive ? "Active" : "Inactive"],
    ],
  });
  return doc.lastAutoTable.finalY + 11;
}

function experienceBody(doc, employee, options, y) {
  const starts = options.joiningDate || employee.joiningDate || employee.createdAt;
  const ends = options.effectiveDate || new Date().toISOString();
  const current = employee.isActive && !options.endEmployment;
  const designation = text(options.designation || employee.designation || employee.role || employee.roleHistory?.[0]?.role?.name, "staff member");
  const message = current
    ? `This is to certify that ${text(employee.username)} has been serving as ${designation} with ${text(employee.school?.name, "Sure Success Point School")} since ${date(starts)} and remains in active service as on ${date(ends)}. During the recorded period, the employee has performed assigned institutional responsibilities in accordance with applicable policies.`
    : `This is to certify that ${text(employee.username)} served as ${designation} with ${text(employee.school?.name, "Sure Success Point School")} from ${date(starts)} to ${date(ends)}. This certificate records the employee's institutional service based on available HR records.`;
  return paragraph(doc, message, y);
}

function workHistory(doc, employee, y) {
  const rows = [
    ...(employee.roleHistory || []).map((entry) => [
      "Access role",
      text(entry.role?.name || entry.role?.code),
      date(entry.startsAt),
      entry.endsAt ? date(entry.endsAt) : "Active / not recorded",
    ]),
    ...(employee.workforceHistory || []).map((entry) => [
      text(entry.assignmentKind),
      text(entry.roleCode),
      date(entry.startsAt),
      entry.endsAt ? date(entry.endsAt) : entry.isActive ? "Active" : "Not recorded",
    ]),
  ];
  autoTable(doc, {
    startY: y,
    margin: { left: 18, right: 18 },
    head: [["Record type", "Responsibility / role", "Start", "End / status"]],
    body: rows.length ? rows : [["HR record", text(employee.role), date(employee.createdAt), employee.isActive ? "Active" : "Inactive"]],
    theme: "grid",
    styles: { font: "helvetica", fontSize: 8, cellPadding: 2.5, textColor: dark },
    headStyles: { fillColor: darkGreen, textColor: 255 },
    alternateRowStyles: { fillColor: [246, 249, 247] },
  });
  return doc.lastAutoTable.finalY + 10;
}

function salaryStatement(doc, payroll, y) {
  const salaries = payroll?.salaries || [];
  autoTable(doc, {
    startY: y,
    margin: { left: 18, right: 18 },
    head: [["Month", "Hours", "Net salary", "Paid", "Remaining", "Status"]],
    body: salaries.length ? salaries.map((salary) => [month(salary.monthYear), salary.totalHoursWorked || "0", money(salary.netSalary), money(salary.salaryPaid), money(salary.remainingSalary), text(salary.paymentStatus)]) : [["No salary records", "—", "—", "—", "—", "—"]],
    theme: "grid",
    styles: { font: "helvetica", fontSize: 7.7, cellPadding: 2.2, textColor: dark },
    headStyles: { fillColor: [48, 81, 111], textColor: 255 },
    alternateRowStyles: { fillColor: [245, 248, 252] },
  });
  return doc.lastAutoTable.finalY + 9;
}

function paymentHistory(doc, payroll, y) {
  const payments = payroll?.payments || [];
  autoTable(doc, {
    startY: y,
    margin: { left: 18, right: 18 },
    head: [["Paid on", "Salary period", "Mode", "Amount", "Recorded by", "Reference / note"]],
    body: payments.length ? payments.map((payment) => [date(payment.paidOn), month(payment.salaryMonth), text(payment.mode), money(payment.amount), text(payment.paidBy), text(payment.note, "—")]) : [["No payment records", "—", "—", "—", "—", "—"]],
    theme: "grid",
    styles: { font: "helvetica", fontSize: 7.4, cellPadding: 2.1, textColor: dark },
    headStyles: { fillColor: [122, 72, 32], textColor: 255 },
    alternateRowStyles: { fillColor: [253, 248, 243] },
  });
  return doc.lastAutoTable.finalY + 9;
}

export function downloadEmployeeDocument({ type, employee, payroll, options = {} }) {
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const normalizedType = String(type || "").toUpperCase();
  const titleByType = {
    OFFER_LETTER: "Offer of Appointment",
    EMPLOYMENT_CERTIFICATE: "Employment Certificate",
    EXPERIENCE_CERTIFICATE: "Experience Certificate",
    WORK_HISTORY: "Work History Report",
    SALARY_STATEMENT: "Salary Statement",
    SALARY_PAYMENT_HISTORY: "Salary Payment History",
  };
  const title = titleByType[normalizedType] || "Employee Document";
  const confidential = normalizedType.includes("SALARY");
  const reference = documentCode(normalizedType, employee, options.reference);
  const preparedEmployee = { ...employee, designation: options.designation, joiningDate: options.joiningDate };

  doc.setProperties({ title: `${title} - ${text(employee.username)}`, subject: "Sure Success Point School employee document", author: "Sure Success Point School Central Administration" });
  header(doc, title, preparedEmployee, reference, confidential);
  let y = 60;

  if (normalizedType === "OFFER_LETTER") {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(...dark);
    doc.text(`Dear ${text(employee.username)},`, 18, y);
    y += 11;
    const designation = text(options.designation || employee.role || employee.roleHistory?.[0]?.role?.name, "staff member");
    y = paragraph(doc, `We are pleased to offer you the position of ${designation} at ${text(employee.school?.name, "Sure Success Point School")}. Your proposed date of joining is ${date(options.joiningDate || employee.createdAt)}. This offer is subject to verification of submitted records, institutional policies, and acceptance of the stated duties.`, y);
    y += 8;
    autoTable(doc, {
      startY: y,
      margin: { left: 18, right: 18 },
      theme: "grid",
      styles: { font: "helvetica", fontSize: 9, cellPadding: 3, textColor: dark },
      body: [
        ["Designation", designation],
        ["Department", text(employee.department)],
        ["School / branch", `${text(employee.school?.name)}${employee.branch?.name ? ` / ${employee.branch.name}` : ""}`],
        ["Proposed monthly compensation", options.monthlyCompensation ? money(options.monthlyCompensation) : "To be confirmed in appointment terms"],
        ["Reference", reference],
      ],
    });
    y = doc.lastAutoTable.finalY + 11;
    y = paragraph(doc, "Please acknowledge acceptance of this offer within the period communicated by the institution. This document is an offer of appointment and does not replace a signed employment agreement where one is required.", y, 174, 9);
  } else if (normalizedType === "EMPLOYMENT_CERTIFICATE") {
    y = experienceBody(doc, preparedEmployee, options, y);
    y += 10;
    y = staffDetails(doc, preparedEmployee, y);
    y = paragraph(doc, "This certificate is issued upon the employee's request for lawful professional, banking, visa, or institutional purposes. It does not disclose compensation or confidential employment terms.", y, 174, 8.7);
  } else if (normalizedType === "EXPERIENCE_CERTIFICATE") {
    y = experienceBody(doc, preparedEmployee, { ...options, endEmployment: true }, y);
    y += 10;
    y = staffDetails(doc, preparedEmployee, y);
    y = paragraph(doc, "The institution thanks the employee for recorded service and issues this certificate from available HR records. Any verification request should quote the reference number above.", y, 174, 8.7);
  } else if (normalizedType === "WORK_HISTORY") {
    y = staffDetails(doc, preparedEmployee, y);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10.5);
    doc.setTextColor(...dark);
    doc.text("Recorded roles and assignments", 18, y);
    y = workHistory(doc, preparedEmployee, y + 6);
    y = paragraph(doc, "This report reflects recorded role and workforce assignments only. It must not be treated as a substitute for an employment agreement or a salary certificate.", y, 174, 8.4);
  } else if (normalizedType === "SALARY_STATEMENT") {
    y = staffDetails(doc, preparedEmployee, y);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10.5);
    doc.setTextColor(...dark);
    doc.text("Recorded monthly salary ledger", 18, y);
    y = salaryStatement(doc, payroll, y + 6);
    y = paragraph(doc, "Amounts are generated from the controlled payroll ledger at the time of issue. This statement is confidential and does not alter payroll balances or payment status.", y, 174, 8.4);
  } else if (normalizedType === "SALARY_PAYMENT_HISTORY") {
    y = staffDetails(doc, preparedEmployee, y);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10.5);
    doc.setTextColor(...dark);
    doc.text("Recorded salary payment history", 18, y);
    y = paymentHistory(doc, payroll, y + 6);
    y = paragraph(doc, "This history reflects recorded disbursement events in the payroll ledger. It is confidential and should be provided only to the named employee or an authorised verifier.", y, 174, 8.4);
  }

  signature(doc, Math.min(Math.max(y + 20, 245), 268), options.signatory);
  footer(doc, reference, confidential);
  doc.save(`SSPS-${title.replaceAll(" ", "-")}-${text(employee.username, "Employee").replaceAll(/[^a-z0-9]+/gi, "-")}.pdf`);
}
