                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    const SizedBox(), // Empty widget to push dropdown to the right
                    DropdownButton<String>(
                      value: _selectedLanguage,
                      icon: const Icon(Icons.language, color: Colors.white),
